"""Serve the psono-web SPA (built client) from Odoo, same origin.

The built web client lives in static/src/psono_web/. index.html is served
only to authenticated Odoo sessions (defense-in-depth; the API itself is
protected by psono tokens). Other assets are served as-is with the SPA's
relative asset paths (publicPath relative in the build).

``config.json`` is special-cased: it is generated by Odoo instead of served
from disk, so operators can change client behaviour without a deploy
(design D1). The static file remains as a fallback.
"""

import json
import logging
import os

from odoo import http

from ..client_config import build_config, load_static_config

_logger = logging.getLogger(__name__)

WEB_ROOT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "static",
    "src",
    "psono_web",
)


class PsonoWebController(http.Controller):
    @http.route(
        "/keykeep/psono/web/",
        type="http", auth="user", csrf=False, methods=["GET"],
    )
    def web_index(self, **kw):
        return self._serve("index.html")

    @http.route(
        "/keykeep/psono/web/config.json",
        type="http", auth="public", csrf=False, methods=["GET"],
    )
    def web_config(self, **kw):
        """Generated client configuration (design D1/D2/D3).

        auth="public" because the login page and the browser extension must
        load it without a session. The session is still *read* when present
        so personal values (language) can be applied.
        """
        try:
            host = http.request.httprequest.host
            session_uid = http.request.session.uid
            config = build_config(http.request.env, host, session_uid)
        except Exception as exc:  # noqa: BLE001
            _logger.warning(
                "keykeep_psono: could not build dynamic config (%s); "
                "falling back to the static file", exc,
            )
            config = load_static_config()
            if config is None:
                return http.Response(status=503)
        response = http.Response(
            json.dumps(config),
            content_type="application/json",
        )
        # Personal values must never be cached by a shared cache.
        response.headers["Cache-Control"] = "no-store"
        return response

    @http.route(
        "/keykeep/psono/web/<path:filepath>",
        type="http", auth="public", csrf=False, methods=["GET"],
    )
    def web_asset(self, filepath, **kw):
        return self._serve(filepath)

    def _serve(self, filepath):
        # prevent path traversal
        filepath = (filepath or "").replace("\\", "/")
        if filepath.startswith("/") or ".." in filepath.split("/"):
            return http.Response(status=404)
        full = os.path.join(WEB_ROOT, filepath)
        if not os.path.isfile(full):
            # SPA fallback: unknown deep links serve index.html so hash
            # routes (#/other/import) work on refresh.
            full = os.path.join(WEB_ROOT, "index.html")
            if not os.path.isfile(full):
                return http.Response(
                    "psono-web is not built yet. Run the build step "
                    "(task 5.3) to place the web client in static/src/psono_web/.",
                    status=503,
                )
        with open(full, "rb") as fh:
            content = fh.read()
        ctype = self._content_type(full)
        return http.Response(content, content_type=ctype)

    @staticmethod
    def _content_type(path):
        ext = os.path.splitext(path)[1].lower()
        return {
            ".html": "text/html; charset=utf-8",
            ".js": "application/javascript",
            ".mjs": "application/javascript",
            ".css": "text/css",
            ".json": "application/json",
            ".png": "image/png",
            ".jpg": "image/jpeg",
            ".jpeg": "image/jpeg",
            ".svg": "image/svg+xml",
            ".ico": "image/x-icon",
            ".woff": "font/woff",
            ".woff2": "font/woff2",
            ".ttf": "font/ttf",
            ".txt": "text/plain",
            ".map": "application/json",
        }.get(ext, "application/octet-stream")
